def test_relink_generated_by_removal() -> None:
    """Existing nodes with generated_by but no written_by must be migrated:
    1. written_by is set to the generated_by value (per type)
    2. generated_by is REMOVED from frontmatter (no code reads it anymore)
    3. rerun is idempotent (no further changes)
    """
    with tempfile.TemporaryDirectory() as td:
        vault = Path(td) / "vault"
        vault.mkdir()
        obj_init.run_apply(vault)

        # Create a direction node with ONLY generated_by, no written_by.
        _write(vault / "objective/direction/DIR-0001-test-migration.md", """\
---
type: direction
id: DIR-0001
created: 2026-06-22
updated: 2026-06-22
generated_by: research
serves_question: Q-0001
related:
  - "[[wiki/concepts/disaggregated-inference]]"
priority: high
status: open
---

## For future Claude
This direction was generated by obj-synth.

## reasoning_pattern
Test reasoning.
""")

        # First relink: should set written_by=research and REMOVE generated_by.
        results1 = objectives.relink(vault, apply=True)
        dir_record = next((r for r in results1 if "DIR-0001" in r["path"]), None)
        assert dir_record is not None, "DIR-0001 record missing"
        assert dir_record["changed"], "first relink should report change for DIR-0001"
        assert dir_record["generated_by_removed"], (
            "first relink should report generated_by_removed=True"
        )

        # Check the file after first relink.
        fm1 = _read_fm(vault / "objective/direction/DIR-0001-test-migration.md")
        assert fm1.get("written_by") == "research", (
            f"DIR-0001: written_by should be 'research' after migration, got {fm1.get('written_by')!r}"
        )
        assert "generated_by" not in fm1, (
            f"DIR-0001: generated_by should have been REMOVED, but still present: {fm1.get('generated_by')!r}"
        )

        # Second relink: must be idempotent (no further changes).
        results2 = objectives.relink(vault, apply=True)
        dir_record2 = next((r for r in results2 if "DIR-0001" in r["path"]), None)
        assert dir_record2 is not None, "DIR-0001 record missing on second run"
        assert not dir_record2["changed"], (
            f"second relink must be idempotent; DIR-0001 should not change, but changed={dir_record2['changed']}"
        )

        # Verify file content is identical.
        fm2 = _read_fm(vault / "objective/direction/DIR-0001-test-migration.md")
        assert fm2.get("written_by") == "research", (
            "DIR-0001: written_by must remain 'research' on second run"
        )
        assert "generated_by" not in fm2, (
            "DIR-0001: generated_by must still be absent on second run"
        )

    print("PASS test_relink_generated_by_removal")


