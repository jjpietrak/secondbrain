def test_relink_hot_md_linkify() -> None:
    """Bare ids in hot.md body become full wikilinks; generated_by -> written_by renamed."""
    with tempfile.TemporaryDirectory() as td:
        vault = Path(td) / "vault"
        vault.mkdir()
        make_hot_fixture(vault)

        objectives.relink(vault, apply=True)

        hot_path = vault / "objective/hot.md"
        hot_text = hot_path.read_text(encoding="utf-8")
        fm = objectives._parse_fm(hot_text)
        body = objectives._body(hot_text)

        # --- frontmatter assertions ---
        assert fm.get("written_by") == "research", (
            f"hot.md: expected written_by=research after rename, got {fm.get('written_by')!r}"
        )
        assert "generated_by" not in fm, (
            f"hot.md: generated_by should have been removed (renamed), still present: "
            f"{fm.get('generated_by')!r}"
        )

        # --- prose linkify assertions ---
        # Q-0001 bare -> full wikilink
        assert "[[objective/research_question/Q-0001-rq-one]]" in body, (
            f"hot.md: Q-0001 should be linkified to full path, body=\n{body}"
        )
        # Verify no bare Q-0001 remains: split out wikilink tokens and check plain segments.
        _plain_segments = re.sub(r"\[\[[^\]]*\]\]", "", body)
        assert "Q-0001" not in _plain_segments, (
            f"hot.md: bare Q-0001 must not remain in non-wikilink text after linkify, "
            f"plain segments=\n{_plain_segments}"
        )

        # DIR-0001 bare -> full wikilink
        assert "[[objective/direction/DIR-0001-dir-one]]" in body, (
            f"hot.md: DIR-0001 should be linkified, body=\n{body}"
        )

        # QP-0001 bare -> full wikilink
        assert "[[objective/research_question_proposal/QP-0001-prop-one]]" in body, (
            f"hot.md: QP-0001 should be linkified, body=\n{body}"
        )

        # TBD-3 must be untouched (wrong prefix / too few digits)
        assert "TBD-3" in body, (
            f"hot.md: TBD-3 must remain untouched, body=\n{body}"
        )
        assert "[[TBD-3]]" not in body, (
            f"hot.md: TBD-3 must NOT be wrapped in a wikilink, body=\n{body}"
        )

        # Already-wrapped Q-0002 link must not be double-wrapped.
        assert "[[objective/research_question/Q-0002-rq-two]]" in body, (
            f"hot.md: pre-existing [[Q-0002]] wikilink must be preserved, body=\n{body}"
        )
        assert "[[[[" not in body, "hot.md: double-wrapped wikilink detected"
        assert body.count("Q-0002") == 1, (
            f"hot.md: Q-0002 should appear exactly once (pre-wrapped), body=\n{body}"
        )

    print("PASS test_relink_hot_md_linkify")


